print("=" * 70)
print("3.6 字符串比较")
print("=" * 70)

print("'abc' == 'abc' :", "abc" == "abc")      # True  内容比较
print("'abc' < 'abd'  :", "abc" < "abd")       # True  字典序（按 Unicode 码点）
print("'A' < 'a'      :", "A" < "a")           # True  65 < 97
print("'10' < '9'     :", "10" < "9")          # True！字符串比较不是数值比较

# 长度不同时：先按共同前缀比较，前缀相同则短的更小
print("'abc' < 'abcd' :", "abc" < "abcd")      # True
print("'abc' == 'ABC' :", "abc" == "ABC")      # False，大小写敏感

# 需要忽略大小写比较时，统一 casefold（比 lower 更彻底，处理 ß 等）
x, y = "Straße", "STRASSE"
print("lower 比较   :", x.lower() == y.lower())    # False
print("casefold 比较:", x.casefold() == y.casefold())  # True

# ★ 内容相等用 ==，不要用 is
a = "hello"
b = "".join(["hel", "lo"])
print("a == b :", a == b)      # True
print("a is b :", a is b)      # 可能是 False（短字符串驻留是实现细节）
