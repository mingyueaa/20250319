print("=" * 70)
print("3.1 创建字符串：引号、三引号、隐式拼接、转义、原始字符串")
print("=" * 70)

s1 = 'single quotes'          # 单引号
s2 = "double quotes"          # 双引号（与单引号完全等价）
s3 = "包含 ' 单引号"           # 外层用双引号，内部可写单引号
s4 = '包含 " 双引号'
print(s1, "|", s2, "|", s3, "|", s4)
# C++: std::string s = "..."；字符用 'a'，Python 里 'a' 也是字符串（长度 1），没有单独的 char 类型

# 三引号：可以跨行，保留所有换行和缩进；也常用于 docstring
multi = """第一行
第二行
    第三行（前面有缩进）"""
print(repr(multi))
# C++11: 原始字符串 R"(第一行
# 第二行)" 才方便跨行；普通字符串需要 "第一行\n第二行"

# 相邻字符串字面量会自动拼接（编译期行为，不是 + 运算）
joined = "Hello, " "World" "!"
print(joined)                 # Hello, World!
# C++: 同样支持 "Hello, " "World" 的相邻拼接

# ---- 转义字符 ----
escapes = {
    "\\n": "换行",
    "\\t": "制表符",
    "\\\\": "反斜杠本身",
    "\\'": "单引号",
    '\\"': "双引号",
    "\\0": "空字符 NUL",
    "\\x41": "十六进制 41 -> A",
    "\\u4e2d": "Unicode 中",
    "\\N{SNOWMAN}": "Unicode 名称 -> 雪人",
}
print("\n转义字符演示：")
for code, desc in escapes.items():
    print(f"  {code:<14} {desc:<18} 实际值 = {eval(chr(34) + code + chr(34))!r}")
# C++: 同样有 \n \t \\ \' \" \0 \x41；但没有 \uXXXX 字符串转义（C++ 有 char16_t 等）

# ---- 原始字符串 r"..."：反斜杠不再转义（写正则、Windows 路径时非常有用）----
path = r"C:\Users\new_folder"
print("\n原始字符串:", path)          # C:\Users\new_folder（\n 没有被解释成换行）
raw = r"\n\t\\"
print("len(r'\\n\\t\\\\') =", len(raw), "| 内容 =", raw)
# C++: 用 R"(C:\Users\new_folder)" 同样避免转义
# 注意：原始字符串不能以单个反斜杠结尾，r"abc\" 是语法错误
