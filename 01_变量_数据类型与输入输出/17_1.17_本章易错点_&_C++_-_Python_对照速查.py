print("=" * 70)
print("1.17 本章易错点 & C++ -> Python 对照速查")
print("=" * 70)

checklist = [
    "变量不需要声明类型，名字只是对象的引用；赋值不复制对象。",
    "改写不可变对象（int/str/tuple）会创建新对象；改写可变对象（list/dict）才原地修改。",
    "True/False/None 首字母大写；判断 None 用 is None。",
    "input() 永远返回 str，参与计算前必须 int()/float() 转换。",
    "int 不会溢出；float 有 0.1+0.2 != 0.3 的精度问题。",
    "没有 ++ / --；请用 x += 1。",
    "没有 const；常量靠全大写命名约定。",
    "Python 不做 char 与 int 的隐式转换：'a' + 1 会报错。",
    "== 比较值，is 比较身份（是否同一个对象）。",
    "Python 的 / 永远是真除法（返回 float），整除用 //。",
]
for i, item in enumerate(checklist, 1):
    print(f"  {i}. {item}")

print("\nC++ -> Python 速查：")
mapping = [
    ("int x = 1;",                 "x = 1"),
    ("std::string s = \"hi\";",    "s = \"hi\""),
    ("true / false",               "True / False"),
    ("nullptr",                    "None"),
    ("std::stoi(s)",               "int(s)"),
    ("std::to_string(x)",          "str(x)"),
    ("std::cout << x << \"\\n\";",  "print(x)"),
    ("std::cin >> x;",             "x = int(input())"),
    ("printf(\"%d\\n\", x);",       "print(f\"{x}\")"),
    ("const int N = 10;",          "N = 10  # 约定全大写"),
]
for cpp, py in mapping:
    print(f"  {cpp:<32} =>  {py}")

