print("=" * 70)
print("1.2 变量：名字绑定对象，动态类型")
print("=" * 70)

age = 18            # C++: int age = 18;
name = "小明"        # C++: std::string name = "小明";
price = 9.9         # C++: double price = 9.9;
is_ok = True        # C++: bool is_ok = true;  （Python 的 True/False 首字母大写）

print(age, name, price, is_ok)

# Python 的变量不是"装值的盒子"，而是"指向对象的标签"（引用）。
# 赋值 = 让这个名字指向右边的对象，所以同一个名字可以先后指向不同类型的对象。
x = 1
print("x =", x, "| type(x) =", type(x))     # type() 返回对象的类型
# C++: std::cout << typeid(x).name();  但 C++ 的 x 类型在编译期就固定了

x = "hello"          # 合法！这叫"动态类型"
print("x =", x, "| type(x) =", type(x))
# C++: x = "hello"; 会编译报错（int 变量不能接收字符串）

# 类型注解（3.6+）：只是给人/工具看的提示，运行时不检查、不强制
score: float = 95.5   # C++: float score = 95.5f;  C++ 是强制的
print("score =", score, "| type =", type(score))
