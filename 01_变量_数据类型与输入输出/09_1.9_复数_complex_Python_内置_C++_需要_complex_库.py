z = 3 + 4j                 # 虚部单位是 j（不是 i），C++: std::complex<double> z(3, 4);
print("z =", z, "| 实部 =", z.real, "| 虚部 =", z.imag)
print("|z| =", abs(z))     # 5.0    C++: std::abs(z)
print("z * z =", z * z)    # 复数乘法
