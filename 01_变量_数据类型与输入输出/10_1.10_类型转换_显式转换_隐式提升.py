print("=" * 70)
print("1.10 类型转换（显式转换 / 隐式提升）")
print("=" * 70)

# --- 字符串 -> 数字 ---
print("int('123')   =", int("123"))         # C++: std::stoi("123")
print("int(' 42 ')  =", int(" 42 "))        # 会自动去掉两端空白
print("float('3.14')=", float("3.14"))      # C++: std::stod("3.14")
print("int('ff', 16)=", int("ff", 16))      # 255
# 注意：int("3.14") 会抛 ValueError，不能直接字符串转 int 小数
try:
    int("3.14")
except ValueError as e:
    print("int('3.14') 抛异常:", e)
    # C++: std::stoi("3.14") 不会报错，只解析出 3（不检查剩余字符时）

# --- 数字 -> 数字 ---
print("int(3.99)   =", int(3.99))           # 3，向零截断
print("float(7)    =", float(7))            # 7.0
print("int(True)   =", int(True))           # 1
print("bool(-1)    =", bool(-1))            # True（非零即真）

# --- 数字/任意对象 -> 字符串 ---
print("str(123)    =", repr(str(123)))      # repr 用来看"字符串的原始形态"
print("str(3.14)   =", str(3.14))

# --- 隐式类型提升：int 与 float 混合运算，结果是 float ---
print("1 + 2.0 =", 1 + 2.0, "| type =", type(1 + 2.0))
# C++: 同样是向"更宽"的类型提升（int -> double）

# 注意：Python 不做"字符 <-> 整数"的隐式转换，'a' + 1 是 TypeError
try:
    "a" + 1
except TypeError as e:
    print("'a' + 1 抛异常:", e)
    # C++: 'a' + 1 是合法的（字符按 ASCII 当整数算），得到 98。这是重要差异！
