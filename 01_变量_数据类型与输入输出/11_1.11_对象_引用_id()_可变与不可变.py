print("=" * 70)
print("1.11 对象、引用、id()、可变与不可变")
print("=" * 70)

a = [1, 2, 3]
b = a                 # 只是让 b 也指向同一个列表对象（没有复制！）
b.append(4)
print("a =", a, "| b =", b)          # a 也变成了 [1, 2, 3, 4]
print("a is b ?", a is b)            # True，同一个对象
# C++: std::vector<int> b = a; 默认是"值拷贝"（深拷贝），a 不受影响。
#      这里 Python 的 b = a 更像 C++ 的 std::vector<int>& b = a;

c = a.copy()          # 显式复制（浅拷贝）
c.append(5)
print("a =", a, "| c =", c)          # a 不受影响
# C++: auto c = a;  值语义拷贝

# id() 返回对象的身份标识（CPython 中就是内存地址）
print("id(a) =", id(a), "| id(b) =", id(b))

# 不可变对象：int / float / str / tuple / bool / None
s1 = "hello"
s2 = s1
s2 = s2 + " world"     # 这里其实是新建了一个字符串对象
print("s1 =", s1, "| s2 =", s2)      # s1 不变
# C++: std::string 是可变的，s2 += " world" 不会新建对象（可能扩容）

# 小整数缓存：-5 ~ 256 的整数在 CPython 中被复用（实现细节，不要依赖）
small_a, small_b = 100, 100
big_a, big_b = int("257"), int("257")    # 运行时构造的 257，不会被缓存
print("small_a is small_b ->", small_a is small_b)     # True（缓存复用）
print("big_a is big_b     ->", big_a is big_b)         # False（两个不同对象）
print("big_a == big_b     ->", big_a == big_b)         # True（值相等）

# 结论：比较"值"用 ==；比较"是不是同一个对象"才用 is（主要用于 None / True / False）。
