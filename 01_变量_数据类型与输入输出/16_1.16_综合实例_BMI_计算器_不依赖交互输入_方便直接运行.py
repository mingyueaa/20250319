print("=" * 70)

# 输入部分（真实场景用 input，这里用固定值以便直接运行）
user_name = "小明"          # 假设来自 input("姓名: ")
weight_kg = 68.5            # 假设来自 float(input("体重(kg): "))
height_m = 1.75             # 假设来自 float(input("身高(m): "))

# 计算 BMI = 体重 / 身高^2
bmi = weight_kg / (height_m ** 2)     # C++: double bmi = weight_kg / (height_m * height_m);

# 分段判断（if/elif 的语法在第 4 章，这里先感受一下）
if bmi < 18.5:
    level = "偏瘦"
elif bmi < 24:
    level = "正常"
elif bmi < 28:
    level = "偏胖"
else:
    level = "肥胖"

print(f"{user_name} 的 BMI = {bmi:.2f}，属于【{level}】")
