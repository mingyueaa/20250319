print("=" * 70)
print("1.4 赋值：基本赋值、多重赋值、链式赋值、交换、解包")
print("=" * 70)

# (1) 基本赋值
a = 10
# C++: int a = 10;

# (2) 多重赋值（同时给多个变量赋值，右侧会先组成一个元组）
p, q, r = 1, 2, 3
# C++11: int p = 1, q = 2, r = 3;  但 Python 右侧是"元组解包"，更通用
print("p, q, r =", p, q, r)

# (3) 链式赋值：三个名字指向同一个对象
a = b = c = 0
print("a, b, c =", a, b, c)
# C++: int a = 0, b = 0, c = 0;

# (4) 交换两个变量：不需要临时变量（右侧先求值成元组，再解包）
left, right = 100, 200
left, right = right, left
print("交换后 left, right =", left, right)
# C++: int t = left; left = right; right = t;  或 std::swap(left, right);

# (5) 星号解包：把"剩下的"打包成一个列表
first, *middle, last = [1, 2, 3, 4, 5]
print("first =", first, "| middle =", middle, "| last =", last)
# C++: 没有直接等价语法，需要手写下标范围

# (6) 带初值的累加（Python 没有 ++ / -- 运算符！）
count = 0
count += 1
count += 1
print("count =", count)
# C++: count++; / ++count;  Python 里请写 count += 1
