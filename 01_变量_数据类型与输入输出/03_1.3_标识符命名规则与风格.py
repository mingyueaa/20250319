print("=" * 70)
print("1.3 标识符命名规则与风格")
print("=" * 70)

# 规则（违反会 SyntaxError）：
#   1) 只能由字母、数字、下划线组成；
#   2) 不能以数字开头；
#   3) 区分大小写（Name 和 name 是两个名字）；
#   4) 不能使用关键字（如 if/for/class/None/True 等）。
# C++: 规则基本相同；但 Python 允许中文等 Unicode 字符做标识符（能跑但不推荐）

my_var = 1
_private = 2          # 单下划线开头：约定"内部使用"
MAX_SIZE = 100        # 全大写：约定"常量"（Python 没有真正的 const）
userName = "驼峰"      # 合法但不推荐，Python 风格用 user_name（snake_case）

print(my_var, _private, MAX_SIZE, userName)

# 社区风格（PEP 8）：
#   变量/函数：snake_case        如 user_name, get_age()
#   类名：PascalCase             如 class MyClass
#   常量：UPPER_CASE             如 MAX_SIZE, PI
# C++: 常见风格是 camelCase / PascalCase / kConstant，注意团队统一即可。
