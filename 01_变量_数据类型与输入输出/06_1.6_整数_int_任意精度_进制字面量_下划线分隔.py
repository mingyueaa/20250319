print("=" * 70)
print("1.6 整数 int：任意精度、进制字面量、下划线分隔")
print("=" * 70)

big = 2 ** 100                     # ** 是幂运算（第 2 章详解）
print("2 ** 100 =", big)
# C++: 没有内置大整数；long long 最多约 9.2e18，再大需要自己实现或 GMP 库。
# Python 的 int 可以任意大，只要内存够，不会溢出。

million = 1_000_000                # 下划线只是视觉分隔，不改变数值
# C++14: 1'000'000  用单引号分隔

# 不同进制的字面量
bin_num = 0b1010        # 二进制 -> 10     C++14: 0b1010
oct_num = 0o17          # 八进制 -> 15     C++:   017
hex_num = 0x1F          # 十六进制 -> 31   C++:   0x1F
print("0b1010 =", bin_num, "| 0o17 =", oct_num, "| 0x1F =", hex_num)

# 进制转换函数
print("bin(10) =", bin(10), "| oct(15) =", oct(15), "| hex(31) =", hex(31))
# C++: std::bitset<8>(10).to_string() / std::oct / std::hex 流操纵符

# 字符串按指定进制解析
print("int('1010', 2) =", int("1010", 2))     # 10
print("int('1F', 16) =", int("1F", 16))       # 31
# C++: std::stoi("1010", nullptr, 2)
