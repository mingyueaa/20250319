print("=" * 70)
print("2.11 运算符优先级与结合性")
print("=" * 70)

# 从高到低（只列常用的）：
#   1. ( )  括号
#   2. **        幂（右结合）        C++: 无此运算符
#   3. +x  -x  ~x  一元
#   4. *  /  //  %                 C++: * / %，无 //
#   5. +  -                        C++: 一致
#   6. <<  >>                      C++: 优先级低于算术，与 Python 一致
#   7. &                           C++: 一致
#   8. ^                           C++: 一致
#   9. |                           C++: 一致
#  10. == != < > <= >= is in       比较（可链式）
#  11. not
#  12. and
#  13. or
#  14. if ... else ...（条件表达式）
#  15. =  +=  :=  等赋值（最低）

print("1 + 2 * 3 =", 1 + 2 * 3)               # 7
print("(1 + 2) * 3 =", (1 + 2) * 3)           # 9
print("2 ** 3 ** 2 =", 2 ** 3 ** 2)           # 512 右结合
print("1 << 2 + 3 =", 1 << 2 + 3)             # 32：先算 2+3，再左移
# C++: 1 << 2 + 3 同样是 32（+ 优先级高于 <<）

print("5 & 3 == 3 =", (5 & 3) == 3)           # 这里是显式括号；不加括号 & 高于 ==
# ★ 提醒：C++ 里 == 优先级高于 &，Python 里 & 高于 ==，两者相反！
#   C++:  if (a & b == c) 实际是 a & (b == c)
#   Python: a & b == c 实际是 (a & b) == c
# 结论：拿不准就加括号，这在两门语言里都是好习惯。

# 结合性：
print("10 - 3 - 2 =", 10 - 3 - 2)             # 5，左结合 (10-3)-2
print("2 ** 2 ** 3 =", 2 ** 2 ** 3)           # 256，右结合 2**(2**3)
