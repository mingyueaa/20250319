print("=" * 70)

score = 72
result = "及格" if score >= 60 else "不及格"
print("result =", result)
# C++: std::string result = (score >= 60) ? "及格" : "不及格";
# Python 的语序是"值 if 条件 else 值"，读作"如果条件成立就取前面的值"。

# 嵌套（可读性差，建议改用 if/elif，或加括号）
n = 0
sign = "正" if n > 0 else ("负" if n < 0 else "零")
print("sign =", sign)

# 用在推导式里也很常见（第 6 章）
nums = [-2, -1, 0, 1, 2]
abs_nums = [v if v >= 0 else -v for v in nums]
print("abs_nums =", abs_nums)
