import math

print("=" * 70)
print("2.1 算术运算符")
print("=" * 70)

a, b = 7, 2

print("a + b  =", a + b)      # 9     C++: a + b
print("a - b  =", a - b)      # 5
print("a * b  =", a * b)      # 14
print("a / b  =", a / b)      # 3.5   ★ 真除法，永远返回 float
print("a // b =", a // b)     # 3     整除（向下取整）
print("a % b  =", a % b)      # 1     取余
print("a ** b =", a ** b)     # 49    幂运算

# C++: 7 / 2 == 3（整数除法，向零截断）；7 / 2.0 == 3.5
#      Python 没有"整数除法"的 /，想要 C++ 的 / 效果必须写 //

# ---- 整除 // 的"向下取整"细节（负数最容易踩坑）----
print("\n负数整除与取余：")
print("-7 // 2 =", -7 // 2, "| -7 % 2 =", -7 % 2)    # -4 和 1
print(" 7 // -2 =", 7 // -2, "|  7 % -2 =", 7 % -2)  # -4 和 -1
print("-7.5 // 2 =", -7.5 // 2)                       # -4.0（floor，不是 -3.0）
# C++: -7 / 2 == -3（向零截断），-7 % 2 == -1（余数符号跟随被除数）
# Python: // 是 math.floor 方向；% 的符号永远跟"除数"一致。
# 数学恒等式在 Python 中成立：a == (a // b) * b + (a % b)

# ---- 幂运算 ** 的结合性与优先级 ----
print("\n2 ** 3 ** 2 =", 2 ** 3 ** 2)     # 512，右结合：2 ** (3 ** 2)
print("-2 ** 2   =", -2 ** 2)             # -4，** 优先级高于一元负号，等于 -(2**2)
print("(-2) ** 2 =", (-2) ** 2)           # 4
# C++: 使用 std::pow(2, 9)；C++ 的 ^ 是异或，不是乘方！

# ---- divmod：同时求商和余数 ----
q, r = divmod(17, 5)
print("divmod(17, 5) =", (q, r))          # (3, 2)
# C++: 需要分别写 17 / 5 和 17 % 5

# ---- 浮点运算 ----
print("7.0 // 2 =", 7.0 // 2, "| type =", type(7.0 // 2))   # 3.0 <class 'float'>
print("2 ** 0.5 =", 2 ** 0.5)             # 1.4142135623730951（平方根）
print("(-8) ** (1/3) =", (-8) ** (1 / 3)) # 复数结果，见下
