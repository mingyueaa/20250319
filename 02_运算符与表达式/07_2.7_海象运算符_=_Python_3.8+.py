# 赋值表达式：在"表达式内部"给变量赋值，并把这个值作为表达式的结果。
data = "hello"
if (length := len(data)) > 3:
    print(f"length = {length}，长度大于 3")
# C++: if (int len = data.size(); len > 3) { ... }   （C++17 的 if 初始化语句）很相似

# 常见用法：while 读入直到结束
numbers = [1, 2, 3, 4, 5]
idx = 0
while (current := numbers[idx] if idx < len(numbers) else None) is not None:
    print("读到:", current)
    idx += 1
# 注意：C++ 的 = 是表达式（可用在条件里），但 Python 的 = 是语句，
#       不能在 if/while 条件里直接用 =，所以才有了 :=。
