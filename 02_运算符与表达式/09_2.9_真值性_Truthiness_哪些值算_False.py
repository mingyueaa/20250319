print("=" * 70)

falsy_values = [False, None, 0, 0.0, 0j, "", [], (), {}, set(), range(0)]
for val in falsy_values:
    print(f"bool({val!r}) -> {bool(val)}")

print("\n除了上面这些，其余对象的 bool() 都是 True：")
print("bool(-1) =", bool(-1), "| bool('0') =", bool("0"), "| bool([0]) =", bool([0]))

