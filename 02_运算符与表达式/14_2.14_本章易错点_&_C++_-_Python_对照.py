print("=" * 70)
print("2.14 本章易错点 & C++ -> Python 对照")
print("=" * 70)

checklist = [
    "/ 是真除法，7 / 2 == 3.5；要 3 就写 7 // 2。",
    "-7 // 2 == -4（向下取整，不是向零截断）；C++ 是 -3。",
    "-7 % 2 == 1（符号随除数）；C++ 是 -1（符号随被除数）。",
    "没有 ++ / --；写 x += 1。",
    "and/or 返回操作数，不是 bool；可用于 a or default 取默认值。",
    "C++ 的 && || ! 对应 Python 的 and or not（不是 & | ~）。",
    "^ 在 Python 里也是异或；乘方是 **。",
    "支持链式比较 0 < x < 10；C++ 里这样写是错的。",
    "is 比较身份，== 比较值；判断 None 一律用 is None。",
    "== 的优先级低于 &，和 C++ 相反，拿不准就加括号。",
    "round() 是半偶舍入（2.5 -> 2），不是 C++ 的 std::round。",
    "赋值是语句不是表达式；条件里赋值要用 :=（3.8+）。",
]
for i, item in enumerate(checklist, 1):
    print(f"  {i}. {item}")

print("\nC++ -> Python 速查：")
mapping = [
    ("a / b  (int 除法)",      "a // b"),
    ("a % b  (-7%2 == -1)",    "a % b  (-7%2 == 1)"),
    ("pow(a, b) / a^b(错)",    "a ** b"),
    ("a && b",                 "a and b"),
    ("a || b",                 "a or b"),
    ("!a",                     "not a"),
    ("a & b (位与)",           "a & b（对 int 一致）"),
    ("a++ / ++a",              "a += 1"),
    ("cond ? x : y",           "x if cond else y"),
    ("x > 0 && x < 10",        "0 < x < 10"),
    ("if (int n = f(); n>0)",  "if (n := f()) > 0:"),
    ("std::round(2.5)",        "round(2.5) -> 2（半偶舍入）"),
]
for cpp, py in mapping:
    print(f"  {cpp:<26} =>  {py}")

print("\n第 2 章结束。建议：把每个 print 里的数字改成负数、浮点数再跑一遍。")
