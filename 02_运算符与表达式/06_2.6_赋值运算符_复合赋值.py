print("2.6 赋值运算符（复合赋值）")
print("=" * 70)

v = 10
v += 5;  print("v += 5   ->", v)     # 15   C++: v += 5;
v -= 3;  print("v -= 3   ->", v)     # 12
v *= 2;  print("v *= 2   ->", v)     # 24
v /= 6;  print("v /= 6   ->", v)     # 4.0  ★ 结果变成 float
v //= 1.5; print("v //= 1.5->", v)   # 2.0
v **= 3; print("v **= 3  ->", v)     # 8.0
v %= 3;  print("v %= 3   ->", v)     # 2.0

# 位运算复合赋值
w = 0b1100
w &= 0b1010; print("w &= 0b1010 ->", w)     # 8
w |= 0b0001; print("w |= 0b0001 ->", w)     # 9
w ^= 0b1111; print("w ^= 0b1111 ->", w)     # 6
w <<= 2;     print("w <<= 2     ->", w)     # 24
w >>= 1;     print("w >>= 1     ->", w)     # 12

# ★ 没有 ++ 和 -- 运算符
# C++: i++; ++i; i--; --i;
# Python: 只能写 i += 1 / i -= 1。写 i++ 会导致 SyntaxError。

# ★ 可变对象的 += 是"原地修改"（会影响到所有指向它的名字）
list_a = [1, 2]
list_b = list_a
list_b += [3]          # 等价于 list_b.extend([3])，原地修改
print("list_a =", list_a, "| list_a is list_b ?", list_a is list_b)   # [1,2,3] True

list_c = [1, 2]
list_d = list_c
list_d = list_d + [3]  # + 会创建新列表，再让 d 指向新对象
print("list_c =", list_c, "| list_c is list_d ?", list_c is list_d)   # [1,2] False
# C++: std::vector 的 += 不存在；push_back 是原地修改，operator+ 返回值拷贝。
