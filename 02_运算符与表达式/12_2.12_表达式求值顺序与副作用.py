# Python 规定：算术/位运算的操作数从左到右求值；
# 赋值语句先算右侧，再绑定名字。
# 与 C++ 不同，Python 不会出现"未定义行为"（如 i = i++ 这种）。

i = 1
i = i + 1
print("i =", i)          # 2
# C++: i = i++ 是未定义行为（C++17 前），Python 根本不允许 ++

# 函数调用时，参数从左到右求值
def show(tag):
    print("  求值:", tag)
    return tag

_ = (show("左"), show("右"))
# C++: 函数参数求值顺序在 C++17 前是未指定的，Python 明确从左到右。
