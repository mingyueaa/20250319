print("=" * 70)
print("2.5 位运算符")
print("=" * 70)

m, n = 0b1100, 0b1010       # 12 和 10
print(f"m = {m:04b}, n = {n:04b}")
print(f"m & n  = {m & n:04b}  ({m & n})")    # 1000 (8)   按位与
print(f"m | n  = {m | n:04b}  ({m | n})")    # 1110 (14)  按位或
print(f"m ^ n  = {m ^ n:04b}  ({m ^ n})")    # 0110 (6)   按位异或
print(f"~m     = {~m}")                     # -13        按位取反
print(f"m << 2 = {m << 2}  ({m << 2:08b})") # 48         左移 = 乘 2^n
print(f"m >> 2 = {m >> 2}")                 # 3          右移 = 向下整除 2^n
# C++: 完全一致（对无符号数）；对负数的 >> 行为 C++ 是"实现定义"，
#      Python 的 >> 一律是算术右移（floor 方向）。

# Python 的整数是"无限位补码"概念，负数位运算不会像 C++ 那样受 32/64 位限制：
print("-5 & 0xFF =", -5 & 0xFF)       # 251，相当于取低 8 位
print("bin(-5) =", bin(-5))           # '-0b101'，Python 显示的是符号 + 绝对值
# C++: -5 存成 0xFFFFFFFB，-5 & 0xFF 也是 251（结果一致，但底层概念不同）

# 常用技巧：判断奇偶、交换、取低位
num = 7
print("num & 1 =", num & 1)                    # 1 表示奇数
print("num | 1 =", num | 1)                    # 强制变奇数
print("num ^ 1 =", num ^ 1)                    # 奇偶翻转（7 -> 6）
